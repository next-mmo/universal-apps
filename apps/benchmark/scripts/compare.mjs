#!/usr/bin/env node
/**
 * compare.mjs — turn a captured tokens report into the round's compare table.
 *
 * Reporting rules (see ../spec/protocol.md): totalTokens is cache-dominated, so the fresh
 * input + output figure is always shown beside it. No currency claim is supported, because every
 * `cost` object observed in this repository is zero.
 *
 * Usage (run from the repository root):
 *   node apps/benchmark/scripts/compare.mjs
 *   node apps/benchmark/scripts/compare.mjs --in apps/benchmark/results/tokens-2026-09-17.json \
 *       --out apps/benchmark/results/compare-2026-09-17.md
 */

import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BENCH = path.resolve(HERE, '..');

const STRATEGY = {
  our: 'shared `@package/pro` CRUD block',
  tailwind: 'plain HTML + Tailwind utilities',
  shadcn: 'vendored local shadcn-style primitives',
};

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === '--in') parsed.input = argv[++index];
    else if (token === '--out') parsed.out = argv[++index];
    else throw new Error(`unknown argument: ${token}`);
  }
  return parsed;
}

const seconds = (ms) => (ms > 0 ? `${(ms / 1000).toFixed(1)} s` : 'n/a');
const grouped = (value) => typeof value === 'number' ? value.toLocaleString('en-US') : value;

function delta(value, best) {
  if (!Number.isFinite(value) || !Number.isFinite(best) || best === 0) return '—';
  const change = ((value - best) / best) * 100;
  if (Math.abs(change) < 0.05) return 'best';
  const sign = change > 0 ? '+' : '−';
  return `${sign}${Math.abs(change).toFixed(1)}%`;
}

function armRows(runs) {
  const byArm = new Map();
  for (const run of runs) {
    if (!run.found) continue;
    const key = run.arm ?? run.label ?? run.sessionId;
    if (!byArm.has(key)) byArm.set(key, []);
    byArm.get(key).push(run);
  }
  return [...byArm.entries()].map(([arm, entries]) => ({
    arm,
    entries,
    n: entries.length,
    medianTotal: median(entries.map((entry) => entry.totalTokens)),
    medianFresh: median(entries.map((entry) => entry.fresh)),
    medianTurns: median(entries.map((entry) => entry.turns)),
    totalTokens: sum(entries.map((entry) => entry.totalTokens)),
    fresh: sum(entries.map((entry) => entry.fresh)),
    input: sum(entries.map((entry) => entry.input)),
    output: sum(entries.map((entry) => entry.output)),
    cacheRead: sum(entries.map((entry) => entry.cacheRead)),
    cacheWrite: sum(entries.map((entry) => entry.cacheWrite)),
    turns: sum(entries.map((entry) => entry.turns)),
    durationMs: sum(entries.map((entry) => entry.durationMs)),
    anyCostNonZero: entries.some((entry) => entry.anyCostNonZero),
  }));
}

function median(values) {
  const clean = values.filter((value) => Number.isFinite(value)).sort((a, b) => a - b);
  if (!clean.length) return NaN;
  const middle = Math.floor(clean.length / 2);
  return clean.length % 2 ? clean[middle] : (clean[middle - 1] + clean[middle]) / 2;
}

const sum = (values) => values.reduce((total, value) => total + (Number.isFinite(value) ? value : 0), 0);

function render(report) {
  const arms = armRows(report.runs ?? []);
  const missing = (report.runs ?? []).filter((run) => !run.found);
  const bestFresh = Math.min(...arms.map((arm) => arm.medianFresh));
  const bestTotal = Math.min(...arms.map((arm) => arm.medianTotal));
  const order = [...arms].sort((a, b) => a.medianFresh - b.medianFresh);
  const winFresh = order[0];
  const winTotal = [...arms].sort((a, b) => a.medianTotal - b.medianTotal)[0];

  const lines = [];
  lines.push('# Agent-token compare — three UI strategies');
  lines.push('');
  lines.push(`> Generated by \`scripts/compare.mjs\` from \`${path.basename(report.input ?? '')}\` on ${new Date().toISOString().slice(0, 10)}`);
  lines.push(`> Round ${report.round ?? '?'} · model \`${report.model ?? 'unrecorded'}\` · reasoning effort \`${report.effort ?? 'unrecorded'}\` · n=${order[0]?.n ?? 0} per arm`);
  lines.push('> Counters are host-reported, summed from each run\'s `messages.jsonl`. Same matched workload in every arm.');
  lines.push('');
  lines.push('## Headline');
  lines.push('');
  if (!arms.length) {
    lines.push('No captured runs. Nothing to compare.');
  } else {
    lines.push(`- **Lowest fresh work (input + output):** ${winFresh.arm} — ${grouped(winFresh.medianFresh)} tokens median.`);
    lines.push(`- **Lowest total tokens (cache reads included):** ${winTotal.arm} — ${grouped(winTotal.medianTotal)} tokens median.`);
    if (winFresh.arm !== winTotal.arm) {
      lines.push('- The two measures disagree. Cache reads dominate `totalTokens`, so the fresh figure is the better proxy for work actually performed; the total is the better proxy for billed context volume.');
    }
  }
  lines.push('');
  lines.push('## Per-arm totals');
  lines.push('');
  lines.push('| Arm | Strategy | n | Turns | input | output | cacheRead | fresh input+output | Δ fresh | totalTokens | Δ total |');
  lines.push('| :-- | :-- | --: | --: | --: | --: | --: | --: | --: | --: | --: |');
  for (const arm of arms) {
    lines.push(
      `| ${arm.arm} | ${STRATEGY[arm.arm] ?? '—'} | ${arm.n} | ${arm.turns} | ${grouped(arm.input)} | ${grouped(arm.output)} | ` +
      `${grouped(arm.cacheRead)} | **${grouped(arm.medianFresh)}** | ${delta(arm.medianFresh, bestFresh)} | ` +
      `**${grouped(arm.medianTotal)}** | ${delta(arm.medianTotal, bestTotal)} |`,
    );
  }
  lines.push('');
  lines.push('`fresh input+output` and `totalTokens` are medians; the raw columns are sums across the arm\'s runs.');
  lines.push('');
  lines.push('## Per-run detail');
  lines.push('');
  lines.push('| Arm | Run | Session | Turns | Cold turns | Cold input | input | output | cacheRead | totalTokens | fresh | cacheRead share | wall clock |');
  lines.push('| :-- | --: | :-- | --: | --: | --: | --: | --: | --: | --: | --: | --: | --: |');
  for (const arm of arms) {
    for (const run of arm.entries) {
      lines.push(
        `| ${arm.arm} | ${run.run ?? '—'} | \`${run.sessionId}\` | ${run.turns} | ${run.coldTurns ?? '—'} | ${grouped(run.coldInput ?? 0)} | ` +
        `${grouped(run.input)} | ${grouped(run.output)} | ` +
        `${grouped(run.cacheRead)} | ${grouped(run.totalTokens)} | ${grouped(run.fresh)} | ` +
        `${(run.cacheReadShare * 100).toFixed(1)}% | ${seconds(run.durationMs)} |`,
      );
    }
  }
  lines.push('');
  lines.push('`Cold turns` are turns after the first that reported no cache read — the whole context was re-sent uncached. `Cold input` is the uncached input those turns account for.');
  lines.push('');
  lines.push('## Limits');
  lines.push('');
  lines.push(`- n=${order[0]?.n ?? 0} per arm. Medians over fewer than three paired runs are not a stable estimate; treat the ordering as provisional until the repeat runs land.`);
  lines.push('- `totalTokens` is cache-dominated. Quote the fresh `input + output` delta beside it, or quote neither.');
  lines.push(`- No currency claim: every recovered \`cost\` object is zero${arms.some((arm) => arm.anyCostNonZero) ? ' — except at least one record in this round, which must be inspected before any monetary statement' : ''}.`);
  const cold = (report.runs ?? []).filter((run) => run.found && (run.excessColdShare ?? 0) >= 0.25);
  if (cold.length) {
    lines.push(
      `- **Provider-cache artifact in this round.** Every arm carries one expected cold turn (the warm-up, before a cache exists), which is excluded here. Beyond it, ${cold.map((run) => `${run.arm} re-sent its whole context uncached on ${run.excessColdTurns} further turns, carrying ${grouped(run.excessColdInput)} tokens (${(run.excessColdShare * 100).toFixed(0)}% of its uncached input)`).join('; ')}. ` +
      'That is a caching effect, not code volume the arm wrote. It inflates the affected arm\'s fresh and total figures, so treat that arm\'s magnitude — not its rank — as provisional until it is re-run.',
    );
  }
  lines.push('- Same machine, same model, same permissions. A different model or a larger change request may reorder the arms.');
  lines.push('- R1–R9 are checked by reading the produced source, not by driving the UI.');
  if (missing.length) {
    lines.push(`- ${missing.length} run(s) could not be captured: ${missing.map((run) => run.arm ?? run.sessionId).join(', ')}.`);
  }
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const input = path.resolve(args.input ?? path.join(BENCH, 'results', 'tokens-latest.json'));
  if (!existsSync(input)) throw new Error(`tokens report not found: ${input}`);
  const report = JSON.parse(await readFile(input, 'utf8'));
  report.input = input;
  const markdown = render(report);
  const out = path.resolve(args.out ?? path.join(BENCH, 'results', `compare-${new Date().toISOString().slice(0, 10)}.md`));
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, `${markdown}\n`, 'utf8');
  console.log(markdown);
  console.log(`\nwrote ${out}`);
}

await main();
